// Exercise windowless Chromium and agent recovery in an isolated guest container.
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { setTimeout as delay } from 'node:timers/promises';
import { runtimeEnv, vmDir, vmName } from '../src/config.mjs';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import WebSocket from 'ws';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { BrowserWorkspaces, recoveredRequest } from '../src/browser-workspace.mjs';
const exec = promisify(execFile);
const name = 'igor-computer-window-test-' + randomUUID().slice(0, 8);
const volume = name + '-profile';
const docker = async (...args) => (await exec('docker', args, { timeout: 60000, maxBuffer: 2 * 1024 * 1024, env: runtimeEnv })).stdout.trim();
const tunnel = action => exec('ssh', ['-F', join(vmDir, 'ssh.config'), '-O', action, '-L', '127.0.0.1:18432:127.0.0.1:18432', 'lima-' + vmName]);
const computer = async (action, args = {}) => JSON.parse(await docker('exec', name, 'python3', '/opt/igor-computer/computer.py', action, JSON.stringify(args)));
const windows = async (action = 'list', args = {}) => JSON.parse(await docker('exec', name, 'python3', '/opt/igor-computer/windows.py', action, ...(action === 'list' ? [] : [args.id || '', args.generation])));
async function waitFor(check) { for (let i = 0; i < 60; i++) { try { const result = await check(); if (result) return result; } catch {} await delay(250); } throw Error('Timed out'); }
let socket, a, b, fresh;
try {
  await tunnel('forward');
  await docker('run', '-d', '--name', name, '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges=true', '--security-opt', 'seccomp=' + process.cwd() + '/container/seccomp.json', '--shm-size', '512m', '--memory', '2g', '--cpus', '2', '-p', '127.0.0.1:18432:9222', '-v', volume + ':/profile', 'igor-computer:0.2.0');
  const version = await waitFor(async () => { const response = await fetch('http://127.0.0.1:18432/json/version'); return response.ok && response.json(); });
  assert.equal((await windows()).windows.length, 0);
  socket = new WebSocket(version.webSocketDebuggerUrl.replace('127.0.0.1:9223', '127.0.0.1:18432').replace('localhost:9223', '127.0.0.1:18432'));
  await new Promise((resolve, reject) => { socket.once('open', resolve); socket.once('error', reject); });
  let sequence = 0;
  const pending = new Map();
  socket.on('message', bytes => { const message = JSON.parse(bytes); const p = pending.get(message.id); if (p) { pending.delete(message.id); message.error ? p.reject(Error(message.error.message)) : p.resolve(message.result); } });
  const cdp = (method, params = {}) => new Promise((resolve, reject) => { const id = ++sequence; pending.set(id, { resolve, reject }); socket.send(JSON.stringify({ id, method, params })); });
  await cdp('Storage.setCookies', { cookies: [{ name: 'window-test', value: 'persistent', url: 'https://recovery.invalid', expires: Date.now() / 1000 + 3600 }] });
  const helper = new BrowserWorkspaces(computer, windows);
  async function client(label) {
    const result = new Client({ name: label, version: '1' });
    await result.connect(new StdioClientTransport({ command: process.execPath, args: ['node_modules/chrome-devtools-mcp/build/src/bin/chrome-devtools-mcp.js', '--browser-url=http://127.0.0.1:18432', '--no-usage-statistics', '--no-performance-crux'], stderr: 'ignore' }));
    return result;
  }
  a = await client('agent-a'); b = await client('agent-b');
  const firstA = await helper.ensure('agent-a', 'agent-a', a, 'list_pages');
  await a.callTool({ name: 'evaluate_script', arguments: { pageId: firstA.pageId, function: '() => { document.title = "agent a"; return true; }' } });
  const firstB = await helper.ensure('agent-b', 'agent-b', b, 'list_pages');
  await b.callTool({ name: 'evaluate_script', arguments: { pageId: firstB.pageId, function: '() => { document.title = "agent b"; return true; }' } });
  const state = await computer('workspace_list');
  const desktopA = state.workspaces.find(w => w.name === 'agent-a').desktop;
  const desktopB = state.workspaces.find(w => w.name === 'agent-b').desktop;
  const windowA = state.windows.find(w => w.desktop === desktopA);
  const windowB = state.windows.find(w => w.desktop === desktopB);
  assert.ok(windowA && windowB);
  await windows('close', { id: windowA.id, generation: state.generation });
  await delay(3000);
  assert.equal((await windows()).windows.filter(w => w.desktop === desktopA).length, 0);
  const recoveryA = await helper.ensure('agent-a', 'agent-a', a, 'evaluate_script');
  const reopened = (await windows()).windows;
  assert.ok(reopened.some(w => w.desktop === desktopA));
  assert.ok(reopened.some(w => w.id === windowB.id && w.desktop === desktopB));
  const evaluated = await a.callTool(recoveredRequest({ name: 'evaluate_script', arguments: { pageId: firstA.pageId, function: '() => { document.title = "reopened agent a"; return true; }' } }, recoveryA));
  assert.ok(!evaluated.isError, JSON.stringify(evaluated));
  await waitFor(async () => (await windows()).windows.some(w => w.desktop === desktopA && w.title.includes('reopened agent a')));
  console.log('PASS: agent recovery selects its own reopened window and preserves another agent’s window');
  fresh = await client('fresh-agent-a');
  const initial = await new BrowserWorkspaces(computer, windows).ensure('agent-a', 'agent-a', fresh, 'evaluate_script');
  await fresh.callTool({ name: 'evaluate_script', arguments: { pageId: initial.pageId, function: '() => { document.title="fresh agent a"; return true; }' } });
  await waitFor(async () => (await windows()).windows.some(w => w.desktop === desktopA && w.title.includes('fresh agent a')));
  assert.equal((await windows()).windows.length, 2);
  console.log('PASS: fresh client starts in its own existing window without adding another window');

  await helper.ensure('agent-a', 'agent-a', a, 'new_page');
  const page = await a.callTool({ name: 'new_page', arguments: { url: 'about:blank' } });
  assert.ok(!page.isError);
  const selectedId = Number(page.content[0].text.match(/(\d+):.*\[selected\]/)[1]);
  await a.callTool({ name: 'evaluate_script', arguments: { pageId: selectedId, function: '() => { document.title = "agent a new tab"; return true; }' } });
  await waitFor(async () => (await windows()).windows.some(w => w.desktop === desktopA && w.title.includes('agent a new tab')));
  const before = await windows();
  for (const window of before.windows) await windows('close', { id: window.id, generation: before.generation });
  await delay(4000);
  assert.equal((await windows()).windows.length, 0);
  assert.equal((await fetch('http://127.0.0.1:18432/json/version')).status, 200);
  assert.ok(!(await a.callTool({ name: 'list_pages', arguments: {} })).isError);
  assert.equal((await windows()).windows.length, 0);
  await helper.ensure('agent-b', 'agent-b', b, 'list_pages');
  const final = await windows();
  assert.equal(final.windows.length, 1);
  assert.equal(final.windows[0].desktop, desktopB);
  const cookies = await cdp('Storage.getCookies');
  assert.ok(cookies.cookies.some(cookie => cookie.name === 'window-test' && cookie.value === 'persistent'));
  console.log('PASS: closing every window leaves desktop empty and CDP alive; next agent command opens only its workspace');
  await computer('workspace_select', { name: 'shared' });
  await computer('workspace_open_browser', { name: 'shared', reuse: true });
  const userCount = (await windows()).windows.length;
  await computer('workspace_open_browser', { name: 'shared', reuse: true });
  assert.equal((await windows()).windows.length, userCount);
  console.log('PASS: launcher focuses existing workspace browser without opening duplicates; logins survive closure');
} finally {
  socket?.close(); await a?.close(); await b?.close(); await fresh?.close();
  await docker('rm', '-f', name).catch(() => {});
  await docker('volume', 'rm', volume).catch(() => {});
  await tunnel('cancel').catch(() => {});
}
